numero1 = int(input("Digite um número: "))
numero2 = int(input("Digite outro número: "))
if numero1 > numero2:
    print(f"{numero1} é maior que {numero2}.")
if numero1 < numero2:
    print(f"{numero1} é menor que {numero2}.")
if numero1 == numero2:
    print(f"{numero1} é igual a {numero2}.")
